//! External debug-loader mods. No shipped game file is modified.
use anyhow::{bail, ensure, Context, Result};
use serde::Deserialize;
use std::{collections::{BTreeMap, BTreeSet}, fs, path::{Path, PathBuf}};

const MANIFEST: &str = "Lua/Matrix/.ascnet-mods.json";
#[derive(Debug, Clone)]
pub struct ModInfo { pub id: String, pub name: String, pub description: String, pub core: bool }
#[derive(Debug, Default)]
pub struct ApplyReport { pub applied: Vec<String>, pub skipped: Vec<String> }
#[derive(Deserialize)]
struct Metadata { #[serde(default)] name: String, #[serde(default)] description: String, #[serde(default)] core: bool }
const CATALOG_MODULE: &str = "XAscNet/XAscNetModCatalog";

fn safe_relative(value: &str) -> Result<()> {
    ensure!(!value.is_empty() && !value.chars().any(|c| c.is_control() || matches!(c, '\\'|':'|'<'|'>'|'\"'|'|'|'?'|'*')), "unsafe path: {value}");
    for part in value.split('/') {
        ensure!(!part.is_empty() && part != "." && part != ".." && !part.ends_with(['.', ' ']), "unsafe path: {value}");
        let stem = part.split('.').next().unwrap_or("").to_ascii_uppercase();
        ensure!(!matches!(stem.as_str(), "CON"|"PRN"|"AUX"|"NUL") && !(stem.len() == 4 && (stem.starts_with("COM") || stem.starts_with("LPT")) && matches!(stem.as_bytes()[3], b'1'..=b'9')), "reserved path: {value}");
    }
    Ok(())
}
fn no_links(path: &Path) -> Result<()> {
    for ancestor in path.ancestors() {
        match fs::symlink_metadata(ancestor) {
            Ok(meta) => {
                ensure!(!meta.file_type().is_symlink(), "symlink forbidden: {}", ancestor.display());
                #[cfg(windows)] {
                    use std::os::windows::fs::MetadataExt;
                    ensure!(meta.file_attributes() & 0x400 == 0, "reparse point forbidden: {}", ancestor.display());
                }
            }
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {},
            Err(e) => return Err(e).with_context(|| format!("inspect {}", ancestor.display())),
        }
    }
    Ok(())
}
fn target(root: &Path, relative: &str) -> Result<PathBuf> {
    safe_relative(relative)?;
    let path = root.join(relative);
    no_links(&path)?;
    Ok(path)
}
/// Every mod directory, core ones included.
fn scan(root: &Path) -> Result<Vec<ModInfo>> {
    no_links(root)?;
    if !root.exists() { return Ok(Vec::new()); }
    let mut mods = Vec::new();
    for entry in fs::read_dir(root)? {
        let entry = entry?;
        let id = entry.file_name().into_string().map_err(|_| anyhow::anyhow!("non-UTF-8 mod directory"))?;
        if id.starts_with('_') || !entry.file_type()?.is_dir() { continue; }
        safe_relative(&id)?;
        let path = target(root, &format!("{id}/mod.json"))?;
        if !path.is_file() { continue; }
        let meta: Metadata = serde_json::from_slice(&fs::read(&path)?).with_context(|| format!("read {}", path.display()))?;
        mods.push(ModInfo { name: if meta.name.is_empty() { id.clone() } else { meta.name }, id, description: meta.description, core: meta.core });
    }
    mods.sort_by(|a,b| a.id.cmp(&b.id));
    Ok(mods)
}
/// Mods the user can toggle; core mods are always installed and never offered.
pub fn discover(root: &Path) -> Result<Vec<ModInfo>> {
    Ok(scan(root)?.into_iter().filter(|m| !m.core).collect())
}
fn lua_string(value: &str) -> String {
    let mut out = String::from("\"");
    for c in value.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c < ' ' || c == '\x7f' => out.push_str(&format!("\\{:03}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}
fn lua_list(items: &[String]) -> String {
    if items.is_empty() { "{ }".to_owned() } else { format!("{{ {} }}", items.iter().map(|i| lua_string(i)).collect::<Vec<_>>().join(", ")) }
}
/// Lua source for the in-game Mod List; `mods` pairs each installed mod with its staged outputs.
fn catalog_lua(mods: &[(&ModInfo, &BTreeMap<String, Vec<u8>>)]) -> String {
    let mut sorted: Vec<_> = mods.iter().collect();
    sorted.sort_by(|a, b| (!a.0.core, &a.0.id).cmp(&(!b.0.core, &b.0.id)));
    let mut out = String::from("-- Generated by the AscNet mod builder; do not edit.\nreturn {\n");
    for (info, staged) in sorted {
        let modules: Vec<String> = staged.keys().filter_map(|p| p.strip_prefix("Lua/Matrix/")?.strip_suffix(".lua")).map(str::to_owned).collect();
        let tables: Vec<String> = staged.keys().filter_map(|p| p.strip_prefix("Table/")).map(str::to_owned).collect();
        out.push_str(&format!("  {{ id = {}, name = {}, description = {}, core = {}, modules = {}, tables = {} }},\n",
            lua_string(&info.id), lua_string(&info.name), lua_string(&info.description), info.core, lua_list(&modules), lua_list(&tables)));
    }
    out.push_str("}\n");
    out
}
fn collect(root: &Path, dir: &Path, files: &mut Vec<String>) -> Result<()> {
    no_links(dir)?;
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        no_links(&entry.path())?;
        if entry.file_type()?.is_dir() { collect(root, &entry.path(), files)?; }
        else {
            ensure!(entry.file_type()?.is_file(), "not a regular file: {}", entry.path().display());
            let rel = entry.path().strip_prefix(root)?.to_str().context("non-UTF-8 mod path")?.replace('\\', "/");
            safe_relative(&rel)?;
            files.push(rel);
        }
    }
    Ok(())
}
fn check_table(data: &[u8]) -> Result<()> {
    ensure!(data.is_ascii(), "table must be ASCII (EN uses GBK)");
    let text = std::str::from_utf8(data)?;
    let lines: Vec<_> = text.split("\r\n").collect();
    ensure!(lines.len() >= 2 && !text.replace("\r\n", "").contains(['\r', '\n']), "table needs CRLF header and rows");
    let width = lines[0].split('\t').count();
    ensure!(!lines[0].is_empty(), "table header is empty");
    for line in &lines[1..] { ensure!(line.is_empty() || line.split('\t').count() == width, "table row width differs from header"); }
    Ok(())
}
fn range(value: &str) -> Result<(usize, usize)> {
    let mut parts = value.split(',');
    let start = parts.next().context("missing hunk position")?.parse()?;
    let count = match parts.next() { Some(s) => s.parse()?, None => 1 };
    ensure!(parts.next().is_none(), "invalid hunk range");
    Ok((start, count))
}
/// Strict unified diff: no offset search, fuzz, implicit newline conversion or multiple files.
fn apply_diff(original: &[u8], patch: &[u8]) -> Result<Vec<u8>> {
    let source: Vec<&[u8]> = original.split_inclusive(|b| *b == b'\n').collect();
    let mut lines: Vec<Vec<u8>> = patch.split_inclusive(|b| *b == b'\n').map(|s| s.to_vec()).collect();
    let mut i = 0;
    while i < lines.len() {
        if lines[i].starts_with(b"\\ No newline at end of file") {
            ensure!(i > 0 && matches!(lines[i-1].first(), Some(b' '|b'+'|b'-')), "misplaced newline marker");
            if lines[i-1].last() == Some(&b'\n') { lines[i-1].pop(); }
            lines.remove(i);
        } else { i += 1; }
    }
    ensure!(lines.len() >= 3 && lines[0].starts_with(b"--- ") && lines[1].starts_with(b"+++ "), "expected unified diff headers");
    let mut output = Vec::new();
    let (mut cursor, mut out_lines, mut pos, mut hunks) = (0usize, 0usize, 2usize, 0usize);
    while pos < lines.len() {
        let header = std::str::from_utf8(&lines[pos])?;
        let fields: Vec<_> = header.split_whitespace().collect();
        ensure!(fields.len() >= 4 && fields[0] == "@@" && fields[3] == "@@", "invalid hunk header");
        let (old, old_count) = range(fields[1].strip_prefix('-').context("missing old range")?)?;
        let (new, new_count) = range(fields[2].strip_prefix('+').context("missing new range")?)?;
        let at = if old_count == 0 { old } else { old.checked_sub(1).context("invalid old line zero")? };
        ensure!(at >= cursor && at <= source.len(), "overlapping or out-of-range hunk");
        for line in &source[cursor..at] { output.extend_from_slice(line); out_lines += 1; }
        cursor = at;
        let new_at = if new_count == 0 { new } else { new.checked_sub(1).context("invalid new line zero")? };
        ensure!(new_at == out_lines, "new hunk position mismatch");
        pos += 1;
        let (mut removed, mut added) = (0,0);
        while pos < lines.len() && !lines[pos].starts_with(b"@@") {
            let line = &lines[pos];
            let kind = *line.first().context("empty patch line")?;
            let body = &line[1..];
            ensure!(matches!(kind, b' '|b'-'|b'+'), "invalid patch line or multiple-file diff");
            if kind != b'+' {
                ensure!(source.get(cursor).copied() == Some(body), "diff does not match shipped module at line {}", cursor + 1);
                cursor += 1; removed += 1;
            }
            if kind != b'-' { output.extend_from_slice(body); added += 1; out_lines += 1; }
            pos += 1;
        }
        ensure!(removed == old_count && added == new_count, "hunk line counts differ");
        hunks += 1;
    }
    ensure!(hunks > 0, "diff has no hunks");
    for line in &source[cursor..] { output.extend_from_slice(line); }
    Ok(output)
}
fn installed(root: &Path) -> Result<Vec<String>> {
    let path = target(root, MANIFEST)?;
    if !path.exists() { return Ok(Vec::new()); }
    let entries: Vec<String> = serde_json::from_slice(&fs::read(path)?)?;
    let mut paths = Vec::new();
    for entry in entries {
        safe_relative(&entry)?;
        let rel = if entry.starts_with("Lua/") || entry.starts_with("Table/") { entry } else { format!("Lua/Matrix/{entry}.lua") };
        ensure!((rel.starts_with("Lua/Matrix/") && rel.ends_with(".lua")) || (rel.starts_with("Table/") && rel.ends_with(".tab")), "manifest entry outside loader roots: {rel}");
        target(root, &rel)?;
        paths.push(rel);
    }
    Ok(paths)
}
fn stopped() -> Result<()> {
    ensure!(!crate::install::game_running()?, "close PGR.exe before changing mods or debug mode");
    Ok(())
}
pub fn read_debug(config_path: &Path) -> Result<bool> {
    no_links(config_path)?;
    if !config_path.try_exists()? { return Ok(false); }
    let value: serde_json::Value = serde_json::from_slice(&fs::read(config_path)?)?;
    Ok(value.get("Client").and_then(|c| c.get("Debug")).and_then(|v| v.as_bool()).unwrap_or(false))
}
fn debug_bytes(config_path: &Path, enabled: bool) -> Result<Vec<u8>> {
    no_links(config_path)?;
    let mut value: serde_json::Value = serde_json::from_slice(&fs::read(config_path)?)?;
    let object = value.as_object_mut().context("server config must be an object")?;
    let client = object.entry("Client").or_insert_with(|| serde_json::json!({}));
    client.as_object_mut().context("Client config must be an object")?.insert("Debug".into(), enabled.into());
    Ok(serde_json::to_vec_pretty(&value)?)
}
fn client_identity(game: &Path) -> Result<(String, String)> {
    let path = target(game, "PGR_Data/app.info")?;
    let info = fs::read_to_string(path).context("read client company/product from PGR_Data/app.info")?;
    let mut lines = info.trim_start_matches('\u{feff}').lines();
    let company = lines.next().context("app.info missing company")?;
    let product = lines.next().context("app.info missing product")?;
    for component in [company, product] {
        safe_relative(component)?;
        ensure!(!component.contains('/'), "app.info identity must be a single path component");
    }
    Ok((company.to_owned(), product.to_owned()))
}
pub fn persistent_directory(game: &Path) -> Result<PathBuf> {
    let (company, product) = client_identity(game)?;
    #[cfg(windows)] {
        use windows::Win32::{UI::Shell::{SHGetKnownFolderPath, FOLDERID_LocalAppDataLow, KF_FLAG_DEFAULT}, System::Com::CoTaskMemFree};
        let folder = unsafe { SHGetKnownFolderPath(&FOLDERID_LocalAppDataLow, KF_FLAG_DEFAULT, None) }.context("resolve LocalLow known folder")?;
        let text = unsafe { folder.to_string() };
        unsafe { CoTaskMemFree(Some(folder.0.cast())) };
        let root = PathBuf::from(text.context("decode LocalLow folder")?);
        ensure!(root.is_absolute(), "LocalLow known folder must be absolute");
        Ok(root.join(company).join(product))
    }
    #[cfg(not(windows))] {
        let _ = (company, product);
        bail!("LocalLow known-folder resolution requires Windows")
    }
}
fn write_config(path: &Path, bytes: &[u8]) -> Result<()> {
    no_links(path)?;
    let parent = path.parent().context("config has no parent")?;
    let temporary = parent.join(format!(".ascnet-debug-{}.tmp", uuid::Uuid::new_v4()));
    let result = (|| -> Result<()> {
        use std::io::Write;
        let mut file = fs::OpenOptions::new().write(true).create_new(true).open(&temporary)?;
        file.write_all(bytes)?;
        file.sync_all()?;
        drop(file);
        #[cfg(windows)]
        crate::local::atomic_replace(&temporary, path)?;
        #[cfg(not(windows))]
        fs::rename(&temporary, path)?;
        Ok(())
    })();
    if result.is_err() && temporary.exists() {
        fs::remove_file(&temporary).context("remove failed config staging file")?;
    }
    result
}
pub fn set_debug(config_path: &Path, enabled: bool) -> Result<()> {
    stopped()?;
    no_links(config_path)?;
    if !config_path.try_exists()? { return Ok(()); }
    let bytes = debug_bytes(config_path, enabled)?;
    write_config(config_path, &bytes).context("save persistent Client.Debug")
}
// Snapshot every touched file before mutation, and restore on I/O failure.
fn replace(root: &Path, outputs: &BTreeMap<String, Vec<u8>>) -> Result<()> {
    let old = installed(root)?;
    let old_set: BTreeSet<_> = old.iter().collect();
    for rel in outputs.keys() {
        let path = target(root, rel)?;
        ensure!(!path.exists() || old_set.contains(rel), "refusing to overwrite unmanaged override: {rel}");
    }
    let mut changes = BTreeMap::new();
    for rel in old.iter().chain(outputs.keys()).chain(std::iter::once(&MANIFEST.to_owned())) {
        let path = target(root, rel)?;
        let previous = match fs::read(&path) { Ok(b) => Some(b), Err(e) if e.kind() == std::io::ErrorKind::NotFound => None, Err(e) => return Err(e.into()) };
        changes.insert(path, previous);
    }
    let result = (|| -> Result<()> {
        for rel in old { let path = target(root, &rel)?; if path.exists() { fs::remove_file(path)?; } }
        for (rel, data) in outputs { let path = target(root, rel)?; fs::create_dir_all(path.parent().context("missing parent")?)?; fs::write(path, data)?; }
        let manifest = target(root, MANIFEST)?;
        if outputs.is_empty() { if manifest.exists() { fs::remove_file(manifest)?; } }
        else { fs::create_dir_all(manifest.parent().context("missing manifest parent")?)?; fs::write(manifest, serde_json::to_vec_pretty(&outputs.keys().collect::<Vec<_>>())?)?; }
        Ok(())
    })();
    if let Err(error) = result {
        let mut failures = Vec::new();
        for (path, bytes) in changes {
            let restore = match bytes { Some(b) => fs::write(&path,b), None => if path.exists() { fs::remove_file(&path) } else { Ok(()) } };
            if let Err(e) = restore { failures.push(format!("{}: {e}",path.display())); }
        }
        bail!("install failed: {error:#}; rollback errors: {}", failures.join("; "));
    }
    Ok(())
}
pub fn clean(_game_dir: &Path, persistent_dir: &Path) -> Result<()> {
    stopped()?;
    replace(persistent_dir, &BTreeMap::new())
}
pub fn apply(game_dir: &Path, persistent_dir: &Path, mods_root: &Path, config_path: &Path, selected: &[String]) -> Result<ApplyReport> {
    stopped()?;
    apply_stopped(game_dir, persistent_dir, mods_root, config_path, selected)
}
fn apply_stopped(game_dir: &Path, persistent_dir: &Path, mods_root: &Path, config_path: &Path, selected: &[String]) -> Result<ApplyReport> {
    let mut outputs = BTreeMap::new();
    let mut destinations = BTreeSet::new();
    let mut report = ApplyReport::default();
    let mut payload = None;
    let all = scan(mods_root)?;
    // Core mods are mandatory: other mods depend on them, so a failed core aborts instead of skipping.
    let mut seen = BTreeSet::new();
    let ids: Vec<&String> = all.iter().filter(|m| m.core).map(|m| &m.id)
        .chain(selected.iter().filter(|id| !all.iter().any(|m| &m.id == *id && m.core)))
        .filter(|id| seen.insert(*id)).collect();
    let mut installed_mods: Vec<(ModInfo, BTreeMap<String, Vec<u8>>)> = Vec::new();
    for id in ids {
        let result = (|| -> Result<BTreeMap<String, Vec<u8>>> {
            ensure!(all.iter().any(|m| &m.id == id), "mod not found in catalog");
            let root = target(mods_root, id)?;
            let mut files = Vec::new(); collect(&root, &root, &mut files)?; files.sort();
            let mut staged = BTreeMap::new();
            for rel in files {
                let (out, data) = if rel.starts_with("Table/") && rel.ends_with(".tab") {
                    let bytes = fs::read(target(&root,&rel)?)?; check_table(&bytes)?; (rel.clone(), bytes)
                } else if rel.ends_with(".lua") && !rel.starts_with("Table/") {
                    (format!("Lua/Matrix/{rel}"), fs::read(target(&root,&rel)?)?)
                } else if let Some(module) = rel.strip_suffix(".diff") {
                    if payload.is_none() { payload = Some(crate::bundle::load_matrix_payload(game_dir)?); }
                    let name = format!("{}.lua", module.rsplit('/').next().context("missing module name")?);
                    let original = crate::bundle::extract_text_asset(payload.as_deref().context("missing bundle payload")?, &name)?;
                    (format!("Lua/Matrix/{module}.lua"), apply_diff(original, &fs::read(target(&root,&rel)?)?)?)
                } else { continue; };
                target(persistent_dir,&out)?;
                let folded = out.to_ascii_lowercase();
                ensure!(folded != format!("lua/matrix/{}.lua", CATALOG_MODULE.to_ascii_lowercase()), "output reserved for the generated mod catalog: {out}");
                ensure!(!destinations.contains(&folded) && !staged.keys().any(|p: &String| p.eq_ignore_ascii_case(&out)), "conflicting output: {out}");
                staged.insert(out,data);
            }
            ensure!(!staged.is_empty(), "mod has no supported files");
            Ok(staged)
        })();
        let info = all.iter().find(|m| &m.id == id);
        match result {
            Ok(staged) => { destinations.extend(staged.keys().map(|s| s.to_ascii_lowercase())); outputs.extend(staged.clone()); report.applied.push(id.clone()); installed_mods.extend(info.map(|i| (i.clone(), staged))); }
            Err(error) if info.is_some_and(|m| m.core) => bail!("core mod {id} failed, nothing installed: {error:#}"),
            Err(error) => report.skipped.push(format!("{id}: {error:#}")),
        }
    }
    if !installed_mods.is_empty() {
        let refs: Vec<_> = installed_mods.iter().map(|(i, s)| (i, s)).collect();
        let out = format!("Lua/Matrix/{CATALOG_MODULE}.lua");
        target(persistent_dir, &out)?;
        outputs.insert(out, catalog_lua(&refs).into_bytes());
    }
    let debug = if outputs.is_empty() || !config_path.try_exists()? { None } else { Some(debug_bytes(config_path,true)?) };
    let previous_config = if debug.is_some() { Some(fs::read(config_path)?) } else { None };
    if let Some(bytes) = debug { write_config(config_path,&bytes).context("save persistent Client.Debug")?; }
    if let Err(error) = replace(persistent_dir,&outputs) {
        if let Some(bytes) = previous_config {
            write_config(config_path,&bytes).with_context(|| format!("restore config after failed mod install: {error:#}"))?;
        }
        return Err(error);
    }
    Ok(report)
}

