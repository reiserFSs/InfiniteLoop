    #[test]
    fn core_always_installed_hidden_and_mandatory() -> Result<()> {
        let root = fs::canonicalize(std::env::temp_dir())?.join(format!("ascnet-mod-core-{}", uuid::Uuid::new_v4()));
        let (mods, data, config) = (root.join("Mods"), root.join("data"), root.join("config.json"));
        fs::create_dir_all(&root)?;
        let result = (|| -> Result<()> {
            fs::write(&config, b"{\"Client\":{\"Debug\":false}}")?;
            write_mod(&mods, "core", br#"{"name":"AscNet core","description":"base","core":true}"#, &[("XAscNet/XAscNetSubMenu.lua", b"return 1\n")])?;
            write_mod(&mods, "b-tab", br#"{"name":"Tab"}"#, &[("Table/Client/T.tab", b"Id\r\n1\r\n")])?;
            write_mod(&mods, "a-lua", br#"{"name":"Lua"}"#, &[("XA.lua", b"return 2\n")])?;
            assert_eq!(discover(&mods)?.iter().map(|m| m.id.as_str()).collect::<Vec<_>>(), ["a-lua", "b-tab"]);
            // No selection: core and its catalog are still installed; a selected "core" id is not duplicated.
            let report = apply_stopped(&root, &data, &mods, &config, &[])?;
            assert_eq!(report.applied, ["core"]);
            assert_eq!(installed(&data)?, ["Lua/Matrix/XAscNet/XAscNetModCatalog.lua", "Lua/Matrix/XAscNet/XAscNetSubMenu.lua"]);
            assert!(read_debug(&config)?);
            let report = apply_stopped(&root, &data, &mods, &config, &["core".into(), "b-tab".into()])?;
            assert_eq!(report.applied, ["core", "b-tab"]);
            let catalog = fs::read_to_string(data.join("Lua/Matrix/XAscNet/XAscNetModCatalog.lua"))?;
            assert!(catalog.contains("id = \"core\"") && catalog.contains("tables = { \"Client/T.tab\" }") && !catalog.contains("a-lua"));
            assert!(catalog.find("\"core\"") < catalog.find("\"b-tab\""));
            // A failing core aborts the whole apply and leaves the previous install alone.
            fs::create_dir_all(mods.join("core/Table"))?;
            fs::write(mods.join("core/Table/Bad.tab"), b"Id\n1\n")?;
            assert!(apply_stopped(&root, &data, &mods, &config, &["a-lua".into()]).is_err());
            assert!(data.join("Table/Client/T.tab").exists() && !data.join("Lua/Matrix/XA.lua").exists());
            // A mod may not claim the generated catalog path.
            fs::remove_dir_all(mods.join("core/Table"))?;
            write_mod(&mods, "c-claim", br#"{}"#, &[("XAscNet/XAscNetModCatalog.lua", b"return {}\n")])?;
            let report = apply_stopped(&root, &data, &mods, &config, &["c-claim".into()])?;
            assert_eq!(report.skipped.len(), 1);
            Ok(())
        })();
        fs::remove_dir_all(root)?;
        result
    }
