    fn write_mod(mods: &Path, id: &str, meta: &[u8], files: &[(&str, &[u8])]) -> Result<()> {
        fs::create_dir_all(mods.join(id))?;
        fs::write(mods.join(id).join("mod.json"), meta)?;
        for (rel, data) in files {
            fs::create_dir_all(mods.join(id).join(rel).parent().context("parent")?)?;
            fs::write(mods.join(id).join(rel), data)?;
        }
        Ok(())
    }
